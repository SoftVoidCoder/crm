function escapeGuideHtml(value) {
    return String(value || '')
        .replace(/&/g, '&amp;')
        .replace(/</g, '&lt;')
        .replace(/>/g, '&gt;')
        .replace(/"/g, '&quot;')
        .replace(/'/g, '&#39;');
}

function buildGuideCard(config) {
    const cards = (config.cards || []).map(card => {
        const listHtml = Array.isArray(card.items) && card.items.length
            ? `<ul class="usage-guide-list">${card.items.map(item => `<li>${escapeGuideHtml(item)}</li>`).join('')}</ul>`
            : '';
        const textHtml = card.text ? `<p class="usage-guide-text">${escapeGuideHtml(card.text)}</p>` : '';
        return `
            <div class="usage-guide-item">
                <h3 class="usage-guide-title">${escapeGuideHtml(card.title)}</h3>
                ${textHtml}
                ${listHtml}
            </div>
        `;
    }).join('');

    return `
        <section class="surface-card surface-card--padded usage-guide no-print" data-guide-id="${escapeGuideHtml(config.id)}">
            <div class="view-heading">
                <span class="view-eyebrow">${escapeGuideHtml(config.eyebrow || 'Памятка')}</span>
                <h2 class="section-title">${escapeGuideHtml(config.title)}</h2>
                <p class="section-subtitle">${escapeGuideHtml(config.subtitle || '')}</p>
            </div>
            <div class="usage-guide-grid">${cards}</div>
        </section>
    `;
}

window.mountSectionGuideForView = function(viewId) {
    const root = document.getElementById(viewId);
    const config = SECTION_GUIDES[viewId];
    if (window.__sectionGuidesEnabled !== true) return;
    if (!root || !config || root.querySelector('.usage-guide')) return;
    root.insertAdjacentHTML('beforeend', buildGuideCard({ ...config, id: viewId }));
};

window.removeMountedSectionGuides = function(viewId) {
    const root = document.getElementById(viewId);
    if (!root) return;
    root.querySelectorAll('.usage-guide[data-guide-id]').forEach(node => node.remove());
};

window.mountAllSectionGuides = function() {
    if (window.__sectionGuidesEnabled !== true) return;
    Object.keys(SECTION_GUIDES).forEach(viewId => {
        window.mountSectionGuideForView(viewId);
    });
};
